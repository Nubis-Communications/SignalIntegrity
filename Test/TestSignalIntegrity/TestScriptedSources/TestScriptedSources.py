import unittest
import SignalIntegrity.Lib as si
import os
import math
import shutil
import tempfile

class TestScriptedSourcesTest(unittest.TestCase,
        si.test.SParameterCompareHelper,si.test.SignalIntegrityAppTestHelper):
    """tests the voltage and current scripted sources, whose waveforms are generated by a python script
    executed with the source's properties and device variables"""
    relearn=True
    debug=False
    checkPictures=True
    copyToBook=False

    def __init__(self, methodName='runTest'):
        si.test.SParameterCompareHelper.__init__(self)
        unittest.TestCase.__init__(self,methodName)
        si.test.SignalIntegrityAppTestHelper.__init__(self,os.path.dirname(os.path.realpath(__file__)))
    def setUp(self):
        unittest.TestCase.setUp(self)
        self.cwd=os.getcwd()
        os.chdir(self.path)
        from SignalIntegrity.App.SignalIntegrityAppHeadless import SignalIntegrityAppHeadless
        import SignalIntegrity.App.Project
        pysi=SignalIntegrityAppHeadless()
        self.UseSinX=SignalIntegrity.App.Preferences['Calculation.UseSinX']
        SignalIntegrity.App.Preferences['Calculation.UseSinX']=False
        self.TextLimit=SignalIntegrity.App.Preferences['Appearance.LimitText']
        SignalIntegrity.App.Preferences['Appearance.LimitText']=60
        self.RoundDisplayedValues=SignalIntegrity.App.Preferences['Appearance.RoundDisplayedValues']
        SignalIntegrity.App.Preferences['Appearance.RoundDisplayedValues']=4
        SignalIntegrity.App.Preferences.SaveToFile()
        pysi=SignalIntegrityAppHeadless()
        SignalIntegrity.App.Preferences['Calculation'].ApplyPreferences()
    def tearDown(self):
        unittest.TestCase.tearDown(self)
        os.chdir(self.cwd)
        from SignalIntegrity.App.SignalIntegrityAppHeadless import SignalIntegrityAppHeadless
        import SignalIntegrity.App.Project
        pysi=SignalIntegrityAppHeadless()
        SignalIntegrity.App.Preferences['Calculation.UseSinX']=self.UseSinX
        SignalIntegrity.App.Preferences['Appearance.LimitText']=self.TextLimit
        SignalIntegrity.App.Preferences['Appearance.RoundDisplayedValues']=self.RoundDisplayedValues
        SignalIntegrity.App.Preferences.SaveToFile()
        pysi=SignalIntegrityAppHeadless()
        SignalIntegrity.App.Preferences['Calculation'].ApplyPreferences()

    def OpenProject(self,filename,args={},writable=False):
        from SignalIntegrity.App.SignalIntegrityAppHeadless import SignalIntegrityAppHeadless
        app=SignalIntegrityAppHeadless()
        self.assertTrue(app.OpenProjectFile(os.path.join(self.path,filename),args,writable),filename+' couldnt be opened')
        return app
    def SimulatedWaveforms(self,filename,args={}):
        result=self.OpenProject(filename,args).Simulate()
        self.assertNotEqual(result,{},filename+' produced none')
        return dict(zip(result['output waveform labels'],result['output waveforms']))
    def assertWaveformsScaled(self,wf,reference,scale,message):
        self.assertEqual(wf.td,reference.td,message+': time descriptors differ')
        self.assertTrue(all(abs(w-scale*r) < 1e-9 for w,r in zip(wf,reference)),message+': values differ')

    # regression tests of each source type through the simulator
    def testVoltageScriptedSourceOnePort(self):
        self.SimulationResultsChecker('VoltageScriptedSourceOnePort.si')
    def testVoltageScriptedSourceTwoPort(self):
        self.SimulationResultsChecker('VoltageScriptedSourceTwoPort.si')
    def testCurrentScriptedSourceOnePort(self):
        self.SimulationResultsChecker('CurrentScriptedSourceOnePort.si')
    def testCurrentScriptedSourceTwoPort(self):
        self.SimulationResultsChecker('CurrentScriptedSourceTwoPort.si')
    def testScriptedSourceVariables(self):
        self.SimulationResultsChecker('ScriptedSourceVariables.si')

    # functional tests
    def testScriptedSourceWaveformMatchesProperties(self):
        """the script receives ho, dur, t0, and fs and produces the waveform on the source's time descriptor"""
        source=self.OpenProject('VoltageScriptedSourceOnePort.si').Device('VS1')
        ho=float(source['ho'].GetValue()); dur=float(source['dur'].GetValue())
        t0=float(source['t0'].GetValue()); fs=float(source['fs'].GetValue())
        K=int(math.ceil(fs*dur))
        td=si.td.wf.TimeDescriptor(ho,K,fs)
        wf=source.Waveform()
        self.assertEqual(wf.td,td,'scripted source time descriptor incorrect')
        expected=si.td.wf.Waveform(td,[math.sin(2.*math.pi*1e9*(ho+k/fs-t0)) if ho+k/fs >= t0 else 0. for k in range(K)])
        self.assertEqual(wf,expected,'scripted source waveform incorrect')
    def testVoltageTwoPortGroundedMatchesOnePort(self):
        onePort=self.SimulatedWaveforms('VoltageScriptedSourceOnePort.si')
        twoPort=self.SimulatedWaveforms('VoltageScriptedSourceTwoPort.si')
        for label in ['VO1','VS1']:
            self.assertWaveformsScaled(twoPort[label],onePort[label],1.,label)
    def testCurrentTwoPortGroundedMatchesOnePort(self):
        onePort=self.SimulatedWaveforms('CurrentScriptedSourceOnePort.si')
        twoPort=self.SimulatedWaveforms('CurrentScriptedSourceTwoPort.si')
        for label in ['VO1','CS1']:
            self.assertWaveformsScaled(twoPort[label],onePort[label],1.,label)
    def testCurrentScriptedSourceIntoResistor(self):
        """20 mA through the 50 ohm resistor to ground produces 1 V at the output"""
        waveforms=self.SimulatedWaveforms('CurrentScriptedSourceOnePort.si')
        self.assertAlmostEqual(max(waveforms['CS1']),0.02,6,'current source amplitude incorrect')
        self.assertAlmostEqual(max(waveforms['VO1']),1.0,3,'output amplitude incorrect')
    def testScriptedSourceProjectArguments(self):
        """the system variable referenced by the device variable can be passed in as a project argument"""
        default=self.SimulatedWaveforms('VoltageScriptedSourceOnePort.si')
        doubled=self.SimulatedWaveforms('VoltageScriptedSourceOnePort.si',{'amplitude':2.0})
        for label in ['VS1','VO1']:
            self.assertWaveformsScaled(doubled[label],default[label],2.,label)

    def testShownScriptedSourceAppearsInOtherWaveforms(self):
        app=self.OpenProject('VoltageScriptedSourceOnePort.si')
        result=app.Simulate()
        self.assertIn('VS1',result['other waveform labels'])
        self.assertIn('VS1',result['output waveform labels'])
        otherIndex=result['other waveform labels'].index('VS1')
        outputIndex=result['output waveform labels'].index('VS1')
        self.assertEqual(result['other waveforms'][otherIndex],result['output waveforms'][outputIndex])

    def testScriptedSourceVariableTypes(self):
        """device variables are passed in by name with float and int variables converted to numbers"""
        source=self.OpenProject('ScriptedSourceVariables.si').Device('VS1')
        context=source.ScriptContext()
        self.assertEqual(context['amplitude'],1.0)
        self.assertIsInstance(context['amplitude'],float)
        self.assertEqual(context['freq'],500e6)
        self.assertIsInstance(context['freq'],float)
        self.assertEqual(context['cycles'],3)
        self.assertIsInstance(context['cycles'],int)
        self.assertEqual(context['shape'],'triangle')
    def testScriptedSourceVariablesBurst(self):
        """the burst is three cycles of a 500 MHz triangle wave starting at t0=10 ns"""
        wf=self.OpenProject('ScriptedSourceVariables.si').Device('VS1').Waveform()
        start=10e-9; end=start+3/500e6
        inside=[v for t,v in zip(wf.Times(),wf.Values()) if start < t < end]
        outside=[v for t,v in zip(wf.Times(),wf.Values()) if not start <= t <= end]
        self.assertAlmostEqual(max(inside),1.0,6,'burst amplitude incorrect')
        self.assertAlmostEqual(min(inside),-1.0,6,'burst amplitude incorrect')
        self.assertTrue(all(v == 0. for v in outside),'waveform not zero outside of the burst')
        halved=self.OpenProject('ScriptedSourceVariables.si',{'amplitude':0.5}).Device('VS1').Waveform()
        self.assertWaveformsScaled(halved,wf,0.5,'burst with amplitude argument')
    def testScriptedSourcePropertiesTakePrecedence(self):
        """a device variable with the same name as a source property does not replace the property"""
        from SignalIntegrity.App.ProjectFile import VariableConfiguration
        source=self.OpenProject('VoltageScriptedSourceOnePort.si').Device('VS1')
        variable=VariableConfiguration()
        variable['Name']='fs'; variable['Type']='float'; variable['Value']='1.0'
        source.variablesList=source.variablesList+[variable]
        self.assertEqual(source.ScriptContext()['fs'],float(source['fs'].GetValue()))
    def testScriptedSourceError(self):
        """a script that doesn't produce output_waveform reports the error and the simulation produces nothing"""
        filename='ScriptedSourceError.si'
        app=self.OpenProject(filename)
        with self.assertRaises(si.SignalIntegrityExceptionWaveform) as error:
            app.Device('VS1').Waveform()
        self.assertIn('output_waveform',error.exception.message)
        self.assertEqual(app.Simulate(),{},filename+' produced something - this is unexpected')
    def testScriptedSourceSaveAndReopen(self):
        """the script and device variables survive saving and reopening the project"""
        directory=tempfile.mkdtemp()
        try:
            filename=os.path.join(directory,'ScriptedSourceVariables.si')
            app=self.OpenProject('ScriptedSourceVariables.si',writable=True)
            original=app.Device('VS1')
            app.SaveProjectToFile(filename)
            reopened=self.OpenProject(filename).Device('VS1')
            self.assertEqual(reopened['script']['Value'],original['script']['Value'],'script changed')
            self.assertEqual([(v['Name'],v['Type'],v['Value']) for v in reopened.variablesList],
                             [(v['Name'],v['Type'],v['Value']) for v in original.variablesList],'device variables changed')
            self.assertEqual(reopened.Waveform(),original.Waveform(),'waveform changed')
        finally:
            os.chdir(self.path)
            shutil.rmtree(directory,ignore_errors=True)

if __name__ == "__main__":
    unittest.main()
